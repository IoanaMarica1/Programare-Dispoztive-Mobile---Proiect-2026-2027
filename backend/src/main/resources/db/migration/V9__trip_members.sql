-- A group trip lists the people travelling. Each member is either a Wanderly user (user_id set) or
-- someone the organiser entered by hand (user_id null). Their preferences are copied at generation
-- time, so the plan's tags still make sense after a member changes their own preferences.
-- A trip without members is a solo trip.

CREATE TABLE trip_members (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              public_id UUID NOT NULL,
                              trip_id BIGINT NOT NULL,
                              user_id BIGINT,
                              name VARCHAR(100) NOT NULL,
                              position INT NOT NULL,

                              CONSTRAINT uk_trip_members_public_id UNIQUE (public_id),
                              CONSTRAINT uk_trip_members_order UNIQUE (trip_id, position),
                              CONSTRAINT fk_trip_members_trip FOREIGN KEY (trip_id) REFERENCES trips (id) ON DELETE CASCADE,
                              -- A member who deletes their account stays on the plan under their name.
                              CONSTRAINT fk_trip_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_trip_members_trip ON trip_members (trip_id);

CREATE TABLE trip_member_interests (
                                       member_id BIGINT NOT NULL,
                                       interest VARCHAR(20) NOT NULL,
                                       CONSTRAINT pk_trip_member_interests PRIMARY KEY (member_id, interest),
                                       CONSTRAINT fk_trip_member_interests FOREIGN KEY (member_id) REFERENCES trip_members (id) ON DELETE CASCADE
);

CREATE TABLE trip_member_priorities (
                                        member_id BIGINT NOT NULL,
                                        priority VARCHAR(20) NOT NULL,
                                        CONSTRAINT pk_trip_member_priorities PRIMARY KEY (member_id, priority),
                                        CONSTRAINT fk_trip_member_priorities FOREIGN KEY (member_id) REFERENCES trip_members (id) ON DELETE CASCADE
);

CREATE TABLE trip_member_paces (
                                   member_id BIGINT NOT NULL,
                                   pace VARCHAR(20) NOT NULL,
                                   CONSTRAINT pk_trip_member_paces PRIMARY KEY (member_id, pace),
                                   CONSTRAINT fk_trip_member_paces FOREIGN KEY (member_id) REFERENCES trip_members (id) ON DELETE CASCADE
);
