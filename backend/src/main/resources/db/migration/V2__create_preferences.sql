CREATE TABLE preferences (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   UUID        NOT NULL,
    user_id     BIGINT      NOT NULL,
    travel_mode VARCHAR(20) NOT NULL,
    priority    VARCHAR(20),
    pace        VARCHAR(20),

    CONSTRAINT uk_preferences_public_id UNIQUE (public_id),
    CONSTRAINT uk_preferences_user      UNIQUE (user_id),
    CONSTRAINT fk_preferences_user      FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_preferences_travel_mode CHECK (travel_mode IN ('SOLO', 'COUPLE', 'FRIENDS', 'FAMILY')),
    CONSTRAINT ck_preferences_priority    CHECK (priority IN ('SOCIAL', 'RELAXATION', 'CULTURE', 'BUDGET')),
    CONSTRAINT ck_preferences_pace        CHECK (pace IN ('RELAXED', 'BALANCED', 'PACKED'))
);

CREATE TABLE preference_interests (
    preferences_id BIGINT      NOT NULL,
    interest       VARCHAR(20) NOT NULL,

    CONSTRAINT pk_preference_interests PRIMARY KEY (preferences_id, interest),
    CONSTRAINT fk_preference_interests_preferences
        FOREIGN KEY (preferences_id) REFERENCES preferences (id) ON DELETE CASCADE,
    CONSTRAINT ck_preference_interests_interest
        CHECK (interest IN ('HISTORY', 'NATURE', 'FOOD', 'NIGHTLIFE', 'ART', 'ADVENTURE'))
);
