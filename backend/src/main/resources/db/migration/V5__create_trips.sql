CREATE TABLE trips (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       public_id UUID NOT NULL,
                       user_id BIGINT NOT NULL,
                       destination VARCHAR(100) NOT NULL,
                       country VARCHAR(100),
                       latitude DOUBLE PRECISION NOT NULL,
                       longitude DOUBLE PRECISION NOT NULL,
                       start_date DATE NOT NULL,
                       end_date DATE NOT NULL,
                       day_start TIME NOT NULL,
                       day_end TIME NOT NULL,
                       created_at TIMESTAMP WITH TIME ZONE NOT NULL,

                       CONSTRAINT uk_trips_public_id UNIQUE (public_id),
                       CONSTRAINT fk_trips_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
                       CONSTRAINT ck_trips_dates CHECK (end_date >= start_date),
                       CONSTRAINT ck_trips_latitude CHECK (latitude BETWEEN -90 AND 90),
                       CONSTRAINT ck_trips_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_trips_user ON trips (user_id);

CREATE TABLE trip_stops (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            trip_id BIGINT NOT NULL,
                            day_number INT NOT NULL,
                            position INT NOT NULL,
                            name VARCHAR(200) NOT NULL,
                            category VARCHAR(50),
                            latitude DOUBLE PRECISION NOT NULL,
                            longitude DOUBLE PRECISION NOT NULL,
                            start_time TIME NOT NULL,
                            duration_minutes INT NOT NULL,

                            CONSTRAINT fk_trip_stops_trip FOREIGN KEY (trip_id) REFERENCES trips (id) ON DELETE CASCADE,
                            CONSTRAINT uk_trip_stops_order UNIQUE (trip_id, day_number, position),
                            CONSTRAINT ck_trip_stops_duration CHECK (duration_minutes > 0)
);