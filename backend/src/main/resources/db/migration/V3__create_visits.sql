CREATE TABLE visits (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id      UUID                     NOT NULL,
    user_id        BIGINT                   NOT NULL,
    objective_name VARCHAR(200)             NOT NULL,
    city           VARCHAR(100)             NOT NULL,
    country        VARCHAR(100)             NOT NULL,
    latitude       DOUBLE PRECISION         NOT NULL,
    longitude      DOUBLE PRECISION         NOT NULL,
    visited_at     TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_visits_public_id      UNIQUE (public_id),
    -- Also serves lookups by user_id, so no separate index is needed.
    CONSTRAINT uk_visit_user_objective  UNIQUE (user_id, objective_name, city, country),
    CONSTRAINT fk_visits_user           FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_visits_latitude       CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_visits_longitude      CHECK (longitude BETWEEN -180 AND 180)
);
